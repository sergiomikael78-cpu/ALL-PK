/**
 * PK MATRIX - MOBILE SYNC & ANDROID KEYBOARD ENGINE
 * Mengelola integrasi handphone Android, generator kamus Gboard/Personal Dictionary,
 * ekspor format PK Mobile Keyboard, dan Interactive Live Simulator (Auto-Expansion).
 */

(function () {
  'use strict';

  // Cache DOM Elements untuk Mobile Modal
  const mobileElements = {
    btnOpenMobile: document.getElementById('btn-open-mobile'),
    modalMobile: document.getElementById('modal-mobile'),
    btnCloseMobile: document.getElementById('btn-close-mobile'),

    // Tabs
    tabGboard: document.getElementById('tab-mobile-gboard'),
    tabApp: document.getElementById('tab-mobile-app'),
    tabSim: document.getElementById('tab-mobile-sim'),
    viewGboard: document.getElementById('view-mobile-gboard'),
    viewApp: document.getElementById('view-mobile-app'),
    viewSim: document.getElementById('view-mobile-sim'),

    // Gboard Tab Elements
    gboardTotalCount: document.getElementById('gboard-total-count'),
    btnDownloadGboardTsv: document.getElementById('btn-download-gboard-tsv'),
    btnCopyGboardSample: document.getElementById('btn-copy-gboard-sample'),
    gboardSamplePreview: document.getElementById('gboard-sample-preview'),

    // App Tab Elements
    appTotalCount: document.getElementById('app-total-count'),
    btnDownloadMobileJson: document.getElementById('btn-download-mobile-json'),
    btnCopyFirebaseUrl: document.getElementById('btn-copy-firebase-url'),

    // Simulator Tab Elements
    simInput: document.getElementById('sim-text-input'),
    simQuickBar: document.getElementById('sim-quick-bar'),
    simStatusBadge: document.getElementById('sim-status-badge'),
    simLastTriggerText: document.getElementById('sim-last-trigger'),
    btnClearSim: document.getElementById('btn-clear-sim')
  };

  // Helper mendapatkan templates saat ini dari window atau localStorage
  function getCurrentTemplates() {
    try {
      const storageKey = window.WorkspaceManager ? window.WorkspaceManager.getStorageKey('TEMPLATES') : 'PK_MASTER_TEMPLATES';
      const raw = localStorage.getItem(storageKey);
      if (raw) {
        return JSON.parse(raw);
      }
    } catch (e) {
      console.warn('Gagal membaca templates dari storage:', e);
    }
    return window.DEFAULT_TEMPLATES || [];
  }

  // Sanitasi teks pemicu (shortcut)
  function cleanTrigger(trig) {
    if (!trig) return '';
    return String(trig).trim();
  }

  // =========================================================================
  // 1. GENERATOR KAMUS GBOARD / ANDROID PERSONAL DICTIONARY
  // Format: <Kata Pengganti/Kalimat>\t<Pemicu/Shortcut>\t<Bahasa/Locale>
  // =========================================================================
  function generateGboardTsv(templates) {
    const validItems = templates.filter(t => t.trigger && t.content);
    const lines = [];

    // Header komentar penjelas (kompatibel dengan parser kamus Android)
    lines.push('# Gboard & Android Personal Dictionary Export');
    lines.push('# Format: Shortcut / Trigger -> Full Replacement Text');
    lines.push('# Generated by PK Matrix Mobile Vault: ' + new Date().toLocaleString());
    lines.push('');

    validItems.forEach(item => {
      const trigger = cleanTrigger(item.trigger);
      let content = String(item.content).replace(/\r\n/g, '\n');
      lines.push(`${content}\t${trigger}\tin-ID`);
    });

    return lines.join('\n');
  }

  // Download Gboard TSV/TXT file
  function downloadGboardDictionary() {
    const templates = getCurrentTemplates();
    const valid = templates.filter(t => t.trigger && t.content);

    if (valid.length === 0) {
      alert('Belum ada template dengan trigger/shortcut. Tambahkan atau import file XML terlebih dahulu!');
      return;
    }

    const tsvContent = generateGboardTsv(templates);
    const blob = new Blob([tsvContent], { type: 'text/tab-separated-values;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `kamus_android_gboard_${new Date().toISOString().slice(0, 10)}.txt`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);

    if (window.showToast) {
      window.showToast('Kamus Android Berhasil Diunduh!', `${valid.length} trigger siap dimasukkan ke HP.`);
    }
  }

  // Download Mobile Keyboard JSON
  function downloadMobileJson() {
    const templates = getCurrentTemplates();
    const payload = {
      version: '1.0',
      exportedAt: new Date().toISOString(),
      generator: 'PK Matrix Mobile Hub',
      totalCount: templates.length,
      templates: templates.map(t => ({
        id: t.id,
        name: t.name || t.title || 'Tanpa Judul',
        trigger: cleanTrigger(t.trigger),
        content: t.content || '',
        category: t.category || 'Umum'
      }))
    };

    const jsonString = JSON.stringify(payload, null, 2);
    const blob = new Blob([jsonString], { type: 'application/json;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `pk_mobile_keyboard_${new Date().toISOString().slice(0, 10)}.json`;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    URL.revokeObjectURL(url);

    if (window.showToast) {
      window.showToast('JSON Mobile Keyboard Diunduh!', `${templates.length} template siap disinkronkan.`);
    }
  }

  // Update Tampilan Tab & Preview Sampel
  function updateMobileStats() {
    const templates = getCurrentTemplates();
    const validWithTrigger = templates.filter(t => t.trigger && t.content);

    if (mobileElements.gboardTotalCount) {
      mobileElements.gboardTotalCount.textContent = `${validWithTrigger.length} Trigger`;
    }
    if (mobileElements.appTotalCount) {
      mobileElements.appTotalCount.textContent = `${templates.length} Template`;
    }

    // Render Preview Sampel
    if (mobileElements.gboardSamplePreview) {
      if (validWithTrigger.length === 0) {
        mobileElements.gboardSamplePreview.innerHTML = '<div class="sim-empty-note">Belum ada template dengan trigger. Buka tab XML untuk impor template atau klik tombol Tambah.</div>';
      } else {
        const samples = validWithTrigger.slice(0, 5);
        let html = '';
        samples.forEach(s => {
          html += `
            <div class="gboard-sample-row">
              <span class="sample-trig font-mono">${escapeHtml(s.trigger)}</span>
              <span class="sample-arrow">➔</span>
              <span class="sample-content">${escapeHtml(s.content.length > 55 ? s.content.slice(0, 55) + '...' : s.content)}</span>
            </div>
          `;
        });
        if (validWithTrigger.length > 5) {
          html += `<div class="sample-more">+ ${validWithTrigger.length - 5} template lainnya...</div>`;
        }
        mobileElements.gboardSamplePreview.innerHTML = html;
      }
    }

    // Render Simulator Quick Bar Pills
    renderSimQuickBar(templates);
  }

  function renderSimQuickBar(templates) {
    if (!mobileElements.simQuickBar) return;
    const valid = templates.filter(t => t.trigger && t.content);
    if (valid.length === 0) {
      mobileElements.simQuickBar.innerHTML = '<span class="sim-pill-empty">Belum ada trigger</span>';
      return;
    }

    // Ambil beberapa trigger populer / teratas
    const pills = valid.slice(0, 8);
    let html = '';
    pills.forEach(p => {
      html += `
        <button type="button" class="sim-quick-pill" data-trigger="${escapeHtml(p.trigger)}" title="${escapeHtml(p.name || p.trigger)}">
          <span class="pill-code">${escapeHtml(p.trigger)}</span>
          <span class="pill-label">${escapeHtml(p.name || p.category || '')}</span>
        </button>
      `;
    });
    mobileElements.simQuickBar.innerHTML = html;

    // Pasang listener klik pada pill untuk inject cepat
    mobileElements.simQuickBar.querySelectorAll('.sim-quick-pill').forEach(btn => {
      btn.addEventListener('click', () => {
        const trig = btn.getAttribute('data-trigger');
        if (!trig || !mobileElements.simInput) return;

        // Cari template yang cocok
        const matched = valid.find(t => cleanTrigger(t.trigger).toLowerCase() === trig.toLowerCase());
        if (matched) {
          insertExpansionIntoSim(matched.content, trig);
        }
      });
    });
  }

  // =========================================================================
  // 2. LIVE SIMULATOR: DETEKSI TRIGGER REAL-TIME (Mirip Keyboard Android)
  // Mengetik "cek/" langsung terhapus dan berganti menjadi kalimat penuh!
  // =========================================================================
  function handleSimInput(e) {
    const input = mobileElements.simInput;
    if (!input) return;

    const val = input.value;
    const cursorPos = input.selectionEnd;
    if (cursorPos === null || cursorPos === undefined) return;

    const templates = getCurrentTemplates();
    const valid = templates.filter(t => t.trigger && t.content);
    if (valid.length === 0) return;

    // Ambil substring sampai posisi kursor saat ini
    const textBeforeCursor = val.slice(0, cursorPos);

    // Cek kecocokan trigger yang berakhiran di posisi kursor
    for (let i = 0; i < valid.length; i++) {
      const trig = cleanTrigger(valid[i].trigger);
      if (!trig) continue;

      // Cek apakah teks sebelum kursor diakhiri oleh trigger ini persis
      if (textBeforeCursor.endsWith(trig)) {
        // Trigger matched!
        const triggerLength = trig.length;
        const replacement = valid[i].content;

        // Ganti teks: potong trigger dan masukkan replacement
        const beforeTrigger = val.slice(0, cursorPos - triggerLength);
        const afterCursor = val.slice(cursorPos);

        const newText = beforeTrigger + replacement + afterCursor;
        input.value = newText;

        // Set kursor tepat setelah teks yang baru ditempel
        const newCursorPos = beforeTrigger.length + replacement.length;
        input.setSelectionRange(newCursorPos, newCursorPos);

        // Feedback Visual & Audio Simulator
        triggerSimFeedback(valid[i], trig);
        break;
      }
    }
  }

  function insertExpansionIntoSim(content, trig) {
    const input = mobileElements.simInput;
    if (!input) return;

    const val = input.value;
    const cursorPos = input.selectionEnd || val.length;
    const before = val.slice(0, cursorPos);
    const after = val.slice(cursorPos);

    input.value = before + (before.length > 0 && !before.endsWith('\n') ? '\n' : '') + content + (after ? '\n' + after : '');
    const newPos = input.value.length;
    input.setSelectionRange(newPos, newPos);
    input.focus();

    triggerSimFeedback({ name: trig, content: content }, trig);
  }

  function triggerSimFeedback(template, triggerName) {
    if (mobileElements.simStatusBadge) {
      mobileElements.simStatusBadge.textContent = `Pemicu Aktif: ${triggerName}`;
      mobileElements.simStatusBadge.classList.add('glow-active');
      setTimeout(() => {
        if (mobileElements.simStatusBadge) {
          mobileElements.simStatusBadge.classList.remove('glow-active');
        }
      }, 1500);
    }

    if (mobileElements.simLastTriggerText) {
      mobileElements.simLastTriggerText.textContent = `"${triggerName}" ➔ ${template.name || 'Template'}`;
    }

    // Efek flash pada input simulator
    if (mobileElements.simInput) {
      mobileElements.simInput.classList.add('flash-cyan');
      setTimeout(() => {
        if (mobileElements.simInput) {
          mobileElements.simInput.classList.remove('flash-cyan');
        }
      }, 400);
    }

    // Haptic vibration jika didukung browser mobile
    if (navigator.vibrate) {
      try {
        navigator.vibrate([40, 30, 40]);
      } catch (err) {}
    }
  }

  // Switch Tab Modal Mobile
  function switchMobileTab(tabName) {
    const tabs = [
      { name: 'gboard', btn: mobileElements.tabGboard, view: mobileElements.viewGboard },
      { name: 'app', btn: mobileElements.tabApp, view: mobileElements.viewApp },
      { name: 'sim', btn: mobileElements.tabSim, view: mobileElements.viewSim }
    ];

    tabs.forEach(t => {
      if (t.name === tabName) {
        if (t.btn) t.btn.classList.add('active');
        if (t.view) t.view.style.display = 'block';
      } else {
        if (t.btn) t.btn.classList.remove('active');
        if (t.view) t.view.style.display = 'none';
      }
    });

    if (tabName === 'sim' && mobileElements.simInput) {
      setTimeout(() => mobileElements.simInput.focus(), 150);
    }
  }

  function openMobileModal() {
    updateMobileStats();
    if (mobileElements.modalMobile) {
      mobileElements.modalMobile.style.display = 'flex';
      switchMobileTab('gboard');
    }
  }

  function closeMobileModal() {
    if (mobileElements.modalMobile) {
      mobileElements.modalMobile.style.display = 'none';
    }
  }

  function escapeHtml(str) {
    if (!str) return '';
    return String(str)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&#039;');
  }

  // =========================================================================
  // INIT LISTENERS
  // =========================================================================
  function initMobileHub() {
    // Re-query in case DOM elements were added dynamically
    mobileElements.btnOpenMobile = document.getElementById('btn-open-mobile');
    mobileElements.modalMobile = document.getElementById('modal-mobile');
    mobileElements.btnCloseMobile = document.getElementById('btn-close-mobile');
    mobileElements.tabGboard = document.getElementById('tab-mobile-gboard');
    mobileElements.tabApp = document.getElementById('tab-mobile-app');
    mobileElements.tabSim = document.getElementById('tab-mobile-sim');
    mobileElements.viewGboard = document.getElementById('view-mobile-gboard');
    mobileElements.viewApp = document.getElementById('view-mobile-app');
    mobileElements.viewSim = document.getElementById('view-mobile-sim');
    mobileElements.gboardTotalCount = document.getElementById('gboard-total-count');
    mobileElements.btnDownloadGboardTsv = document.getElementById('btn-download-gboard-tsv');
    mobileElements.btnCopyGboardSample = document.getElementById('btn-copy-gboard-sample');
    mobileElements.gboardSamplePreview = document.getElementById('gboard-sample-preview');
    mobileElements.appTotalCount = document.getElementById('app-total-count');
    mobileElements.btnDownloadMobileJson = document.getElementById('btn-download-mobile-json');
    mobileElements.btnCopyFirebaseUrl = document.getElementById('btn-copy-firebase-url');
    mobileElements.simInput = document.getElementById('sim-text-input');
    mobileElements.simQuickBar = document.getElementById('sim-quick-bar');
    mobileElements.simStatusBadge = document.getElementById('sim-status-badge');
    mobileElements.simLastTriggerText = document.getElementById('sim-last-trigger');
    mobileElements.btnClearSim = document.getElementById('btn-clear-sim');

    // Tombol Open & Close Modal
    if (mobileElements.btnOpenMobile) {
      mobileElements.btnOpenMobile.addEventListener('click', openMobileModal);
    }
    if (mobileElements.btnCloseMobile) {
      mobileElements.btnCloseMobile.addEventListener('click', closeMobileModal);
    }

    // Klik luar modal untuk menutup
    if (mobileElements.modalMobile) {
      mobileElements.modalMobile.addEventListener('click', (e) => {
        if (e.target === mobileElements.modalMobile) {
          closeMobileModal();
        }
      });
    }

    // Navigasi Tabs
    if (mobileElements.tabGboard) {
      mobileElements.tabGboard.addEventListener('click', () => switchMobileTab('gboard'));
    }
    if (mobileElements.tabApp) {
      mobileElements.tabApp.addEventListener('click', () => switchMobileTab('app'));
    }
    if (mobileElements.tabSim) {
      mobileElements.tabSim.addEventListener('click', () => switchMobileTab('sim'));
    }

    // Action Downloads
    if (mobileElements.btnDownloadGboardTsv) {
      mobileElements.btnDownloadGboardTsv.addEventListener('click', downloadGboardDictionary);
    }
    if (mobileElements.btnDownloadMobileJson) {
      mobileElements.btnDownloadMobileJson.addEventListener('click', downloadMobileJson);
    }

    // Copy Sample Gboard Text
    if (mobileElements.btnCopyGboardSample) {
      mobileElements.btnCopyGboardSample.addEventListener('click', () => {
        const templates = getCurrentTemplates();
        const valid = templates.filter(t => t.trigger && t.content);
        if (valid.length === 0) {
          alert('Belum ada template dengan trigger.');
          return;
        }
        const sampleText = valid.slice(0, 5).map(t => `${t.trigger} ➔ ${t.content}`).join('\n\n');
        navigator.clipboard.writeText(sampleText).then(() => {
          if (window.showToast) {
            window.showToast('Daftar Sampel Tersalin!', 'Bisa dicoba tempel di catatan HP.');
          }
        });
      });
    }

    // Copy Firebase Database URL
    if (mobileElements.btnCopyFirebaseUrl) {
      mobileElements.btnCopyFirebaseUrl.addEventListener('click', () => {
        const url = (window.FIREBASE_CONFIG && window.FIREBASE_CONFIG.databaseURL) 
          ? window.FIREBASE_CONFIG.databaseURL 
          : 'https://pk-matrix2-default-rtdb.firebaseio.com';
        navigator.clipboard.writeText(url).then(() => {
          if (window.showToast) {
            window.showToast('URL Firebase Tersalin!', 'Gunakan URL ini di aplikasi keyboard Android.');
          }
        });
      });
    }

    // Live Simulator Events
    if (mobileElements.simInput) {
      mobileElements.simInput.addEventListener('input', handleSimInput);
      mobileElements.simInput.addEventListener('keyup', (e) => {
        if (e.key === '/' || e.key === ' ' || e.key === 'Enter') {
          handleSimInput(e);
        }
      });
    }

    if (mobileElements.btnClearSim) {
      mobileElements.btnClearSim.addEventListener('click', () => {
        if (mobileElements.simInput) {
          mobileElements.simInput.value = '';
          mobileElements.simInput.focus();
        }
        if (mobileElements.simStatusBadge) {
          mobileElements.simStatusBadge.textContent = 'Menunggu Pemicu...';
          mobileElements.simStatusBadge.classList.remove('glow-active');
        }
        if (mobileElements.simLastTriggerText) {
          mobileElements.simLastTriggerText.textContent = '-';
        }
      });
    }
  }

  // Ekspor API ke global window
  window.MobileHub = {
    init: initMobileHub,
    open: openMobileModal,
    close: closeMobileModal,
    updateStats: updateMobileStats,
    generateGboardTsv: generateGboardTsv
  };

  // Jalankan init setelah DOM siap
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initMobileHub);
  } else {
    initMobileHub();
  }
})();
